const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();
const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const shapes = new Map();
for (const phosphor of new Set(Object.values(ICONS))) {
  const file = `node_modules/@phosphor-icons/core/assets/duotone/${kebab(phosphor)}-duotone.svg`;
  const svg = readFileSync(file, "utf8");
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  shapes.set(phosphor, inner.replace(/ ([a-z]+(?:-[a-z]+)+)=/g, (_, attr) => ` ${camel(attr)}=`));
}

const out = [
  `// Generated by scripts/gen-icons.mjs from Phosphor's duotone icons (MIT); do not edit by hand.
// Decorative icons are hidden from assistive technology at the call site (aria-hidden); an icon
// that stands alone has an aria-label.

import type { ComponentType, ReactNode, SVGProps } from "react";

export type Icon = ComponentType<Omit<SVGProps<SVGSVGElement>, "ref"> & { size?: number | string }>;

const icon =
  (shapes: ReactNode): Icon =>
  ({ size = 24, ...rest }) => (
    <svg viewBox="0 0 256 256" width={size} height={size} fill="currentColor" {...rest}>
      {shapes}
    </svg>
  );

`,
];
for (const [name, phosphor] of Object.entries(ICONS)) {
  out.push(`export const ${name}: Icon = icon(<>${shapes.get(phosphor)}</>);\n`);
}
writeFileSync("src/icons.tsx", out.join(""));
