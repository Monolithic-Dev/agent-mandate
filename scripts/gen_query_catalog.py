"""Generate docs/query-catalog.md from the Cypher files the product actually runs.

    python scripts/gen_query_catalog.py            # rewrite the catalog
    python scripts/gen_query_catalog.py --check    # fail if it is out of date (CI)

The hackathon requires the README to list the Cypher queries the product depends on; generating
the list from the files means it cannot drift from the code.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QUERIES = ROOT / "src" / "mandate" / "graph" / "queries"
OUT = ROOT / "docs" / "query-catalog.md"


def purpose(stem: str) -> str:
    kind = "Read" if stem.startswith("q") else "Write"
    words = stem.split("_", 1)[1].replace("_", " ")
    return f"{kind}: {words}"


def render() -> str:
    files = sorted(QUERIES.glob("*.cypher"))
    lines = [
        "# Cypher query catalog",
        "",
        "Generated by `scripts/gen_query_catalog.py` from `src/mandate/graph/queries/`; "
        "do not edit by hand.",
        f"{len(files)} queries. Every value travels as a parameter; the product runs only "
        "these named files (see `graph/client.py`). Reads are `q*`, writes are `w*`.",
        "",
        "| Query | What it does |",
        "|---|---|",
    ]
    lines += [f"| `{f.stem}` | {purpose(f.stem)} |" for f in files]
    for f in files:
        body = f.read_text(encoding="utf-8").strip()
        lines += ["", f"## {f.stem}", "", "```cypher", body, "```"]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/query-catalog.md is out of date; run scripts/gen_query_catalog.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
